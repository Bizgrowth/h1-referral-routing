st.set_page_config(page_title="H1 Referral Routing", layout="wide")
st.markdown(CSS, unsafe_allow_html=True)

real_path = Path(os.environ.get("H1_INPUT") or importer.default_input(ROOT / "data"))
is_demo = not real_path.exists()
if is_demo:
    path = ROOT / "output" / "demo" / "Referrals-demo.xlsx"
    if not path.exists():
        demo_data.write(path)
    log_path = ROOT / "logs" / "demo-decisions.jsonl"
else:
    path, log_path = real_path, ROOT / "logs" / "decisions.jsonl"


@st.cache_resource
def load(source: str, modified: float):
    result = importer.load(source)
    train, test = scoring.split(result.rows)
    vendors = sorted(v for v in result.rows["answer_vendor"].unique() if v)
    return Suggester.fit(train), test.to_dict("records"), vendors, quality.report(result.rows)


def read_log() -> list:
    if not log_path.exists():
        return []
    return [json.loads(line) for line in log_path.read_text(encoding="utf-8").splitlines() if line.strip()]


suggester, test_rows, vendors, q = load(str(path), path.stat().st_mtime)
decisions = read_log()
done = {d["row_id"] for d in decisions}
queue = [row for row in test_rows if row["row_id"] not in done]
total = len(test_rows)

with st.sidebar:
    st.markdown("### H1 Referral Routing")
    st.markdown("**🔒 Local only · de-identified data**")
    st.caption("Runs entirely on this computer. No referral leaves it, and no vendor is assigned "
               "without a coordinator's decision.")
    st.progress((total - len(queue)) / total if total else 0, text=f"{total - len(queue)} of {total} reviewed")
    if is_demo:
        st.caption("Demo mode: fictional referrals.")
        if st.button("Restart demo queue", width="stretch"):
            log_path.unlink(missing_ok=True)
            st.rerun()

if is_demo:
    st.markdown('<div class="demo-note">Demo mode. These referrals are fictional, generated to show how the '
                'screen works. Nothing here is a real case or a measured result.</div>', unsafe_allow_html=True)

quality_tab, review_tab, results_tab = st.tabs(["Intake quality", "Review queue", "Review time"])


def slip_html(row) -> str:
    by_field = issues_by_field(row)
    out = []
    for field, label in FIELDS:
        value = str(row.get(field, "")).strip()
        shown = escape(value) if value else ("None given" if field.startswith("diag") else
                                             "Removed by privacy filter" if field in row.get("_privacy", "") else "Blank")
        note = f'<span class="flag-note">{escape(by_field[field])}</span>' if field in by_field else ""
        out.append(f'<div class="slip-row{" flagged" if field in by_field else ""}">'
                   f'<div class="slip-label">{label}</div>'
                   f'<div class="slip-value{"" if value else " empty"}">{shown}{note}</div></div>')
    return '<div class="card">' + "".join(out) + "</div>"


def vendors_html(suggestions) -> str:
    if not suggestions:
        return '<div class="card empty-card">No vendor history matches this referral. Assign a vendor below or reject it.</div>'
    top = max(s.count for s in suggestions) or 1
    items = [f'<div class="vendor{" top" if i == 0 else ""}"><div class="rank">{i + 1}</div><div>'
             f'<div class="vname">{escape(s.vendor)}</div><div class="reason">{escape(s.reason)}</div>'
             f'<div class="meter"><span style="width:{max(6, 100 * s.count / top):.0f}%"></span></div></div></div>'
             for i, s in enumerate(suggestions)]
    return '<div class="card">' + "".join(items) + "</div>"


with review_tab:
    if not queue:
        st.success(f"All {total} referrals are reviewed. Open Results to see the totals.")
    else:
        row = queue[0]
        row_id = int(row["row_id"])
        if st.session_state.get("current") != row_id:
            st.session_state.current = row_id
            st.session_state.opened = time.monotonic()
        routed = scoring.route(row, suggester)
        flags, suggestions = routed["flags"], routed["suggestions"]

        st.markdown(f'<div class="ref-head"><h2>Referral {row_id}</h2><span class="ref-meta">Received '
                    f'{row["year"]}. Number {total - len(queue) + 1} of {total} in this queue.</span></div>',
                    unsafe_allow_html=True)
        left, right = st.columns([1.05, 1], gap="large")
        with left:
            st.markdown('<p class="panel-title">Referral details</p>' + slip_html(row) +
                        (f'<p class="summary warn">{len(flags)} item{"s" if len(flags) > 1 else ""} to fix '
                         f'before this referral can be routed.</p>' if flags else
                         '<p class="summary ok">All required details present.</p>'), unsafe_allow_html=True)
        with right:
            st.markdown('<p class="panel-title">Suggested vendors</p>' + vendors_html(suggestions),
                        unsafe_allow_html=True)

        def decide(decision: str, vendor):
            record = {"logged_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "row_id": row_id,
                      "decision": decision, "vendor": vendor,
                      "top_suggestion": suggestions[0].vendor if suggestions else None,
                      "flags": len(flags), "seconds": round(time.monotonic() - st.session_state.opened, 1)}
            log_path.parent.mkdir(exist_ok=True)
            with log_path.open("a", encoding="utf-8") as f:
                f.write(json.dumps(record) + "\n")
            st.session_state.current = None
            st.rerun()

        st.markdown('<p class="panel-title" style="margin-top:22px">Your decision</p>', unsafe_allow_html=True)
        approve, change, reject = st.columns([1, 1.3, 1], vertical_alignment="bottom")
        if approve.button(f"Approve {suggestions[0].vendor}" if suggestions else "Approve", type="primary",
                          disabled=not suggestions, width="stretch"):
            decide("approve", suggestions[0].vendor)
        choice = change.selectbox("Assign a different vendor", vendors)
        if change.button("Change vendor", width="stretch"):
            decide("change", choice)
        if reject.button("Reject", width="stretch"):
            decide("reject", None)
        st.caption("Each decision and the time it took are saved on this computer only.")

with results_tab:
    seconds = [d["seconds"] for d in decisions if isinstance(d.get("seconds"), (int, float))]
    manual = st.number_input("Manual review time per referral, in seconds", min_value=0, value=165, step=5)
    counts = {k: sum(d["decision"] == k for d in decisions) for k in ("approve", "change", "reject")}
